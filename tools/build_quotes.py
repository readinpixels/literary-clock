#!/usr/bin/env python3
"""Convert a Literature Clock CSV into the plugin's Lua data files.

Usage: build_quotes.py <quotes.csv> <output dir>

Input: the pipe-separated CSV of cdmoro/literature-clock
(Time|Id|Quote time|Quote|Title|Author|SFW|Source locale).

Output: one file per hour, <output dir>/HH.lua, returning

    { ["HH:MM"] = { { quote, title, author, sfw }, ... }, ... }

The quote string carries its styling as control characters, so the Lua side
only has to split on them:

    \\1 ... \\2   italic (the source's <em>)
    \\3 ... \\4   the time phrase, drawn highlighted
    \\n           line break (the source's <br>)
"""
import csv
import os
import re
import sys

EM_ON, EM_OFF, T_ON, T_OFF = "\x01", "\x02", "\x03", "\x04"


def parse_markup(text):
    """Return [(char, italic)] for a quote with <em> and <br> tags."""
    text = re.sub(r"\s*<br\s*/?>\s*", "\n", text)
    out = []
    italic = False
    for part in re.split(r"(</?em>)", text):
        if part == "<em>":
            italic = True
        elif part == "</em>":
            italic = False
        else:
            out.extend((c, italic) for c in part)
    return out


def normalise(chars):
    """Collapse runs of spaces and trim, keeping the per-char style."""
    res = []
    for c, it in chars:
        if c in " \t\r":
            c = " "
            if res and res[-1][0] in " \n":
                continue
        if c == "\n" and res and res[-1][0] == " ":
            res.pop()
        res.append((c, it))
    while res and res[0][0] in " \n":
        res.pop(0)
    while res and res[-1][0] in " \n":
        res.pop()
    return res


def encode(chars, phrase):
    plain = "".join(c for c, _ in chars)
    start = plain.lower().find(phrase.lower().strip()) if phrase.strip() else -1
    end = start + len(phrase.strip()) if start >= 0 else -1
    out = []
    italic = False
    for i, (c, it) in enumerate(chars):
        if i == start:
            out.append(T_ON)
        if it != italic:
            out.append(EM_ON if it else EM_OFF)
            italic = it
        out.append(c)
        if i == end - 1:
            if italic:
                # close and reopen italics around the end marker so the
                # markers always nest the same way
                out.append(EM_OFF)
                out.append(T_OFF)
                out.append(EM_ON)
            else:
                out.append(T_OFF)
    if italic:
        out.append(EM_OFF)
    return "".join(out), start >= 0


def lua_str(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif o < 32:
            out.append("\\%03d" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main(src, dst):
    by_hour = {}
    missing = 0
    total = 0
    with open(src, encoding="utf-8", newline="") as f:
        reader = csv.reader(f, delimiter="|", quoting=csv.QUOTE_NONE)
        header = next(reader)
        assert header[0] == "Time" and header[3] == "Quote", header
        for row in reader:
            if len(row) < 7:
                continue
            time, _id, phrase, quote, title, author, sfw = row[:7]
            if not re.fullmatch(r"\d\d:\d\d", time):
                continue
            text, found = encode(normalise(parse_markup(quote)), phrase)
            if not found:
                missing += 1
            total += 1
            by_hour.setdefault(time[:2], {}).setdefault(time, []).append(
                (text, title.strip(), author.strip(), sfw.strip().lower() == "true"))

    os.makedirs(dst, exist_ok=True)
    for hour in ("%02d" % h for h in range(24)):
        lines = ["-- Generated by tools/build_quotes.py from the Literature Clock",
                 "-- dataset. Do not edit by hand. See NOTICE.md for credits.",
                 "return {"]
        for time in sorted(by_hour.get(hour, {})):
            lines.append("[%s]={" % lua_str(time))
            for text, title, author, sfw in by_hour[hour][time]:
                lines.append("{%s,%s,%s,%s}," % (
                    lua_str(text), lua_str(title), lua_str(author),
                    "true" if sfw else "false"))
            lines.append("},")
        lines.append("}")
        with open(os.path.join(dst, hour + ".lua"), "w", encoding="utf-8") as out:
            out.write("\n".join(lines) + "\n")
    print("%d quotes, %d without a located time phrase" % (total, missing))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
